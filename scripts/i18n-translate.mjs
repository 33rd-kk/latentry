// Generates a UI catalog for another language from locales/en.json, through a
// translation provider you plug in.
//
//   TRANSLATOR=<provider> node scripts/i18n-translate.mjs <locale> [--all] [--dry-run]
//   npm run i18n:translate -- de
//
// <provider> is a module in scripts/translators/ (see the README there). Only
// keys that are missing, or whose English changed since they were translated,
// are sent; --all sends every key. What each translation was made from is kept
// in locales/.sources/<locale>.json, which is how a changed English string is
// noticed.
//
// `{name}` placeholders and `<b>…</b>` markup are swapped for opaque tokens
// before sending and put back after, so a provider cannot translate or drop
// them. A translation that comes back without every token is rejected and the
// key stays in English.
//
//   node scripts/i18n-translate.mjs --check
//
// lists, for every catalog, the keys that are missing, stale or broken, and
// exits non-zero if any are broken.

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..')
const LOCALES_DIR = path.join(ROOT, 'locales')
const SOURCES_DIR = path.join(LOCALES_DIR, '.sources')
const SOURCE_LOCALE = 'en'
const LOCALE_PATTERN = /^[a-z]{2,3}(-[A-Za-z0-9]{2,8})*$/

const readJson = (file, fallback) => (existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : fallback)
const writeJson = (file, value) => writeFileSync(file, JSON.stringify(value, null, 2) + '\n')

/** { "a.b": "text" } from { a: { b: "text" } }. */
export function flatten(tree, prefix = '', out = {}) {
  for (const [key, value] of Object.entries(tree)) {
    const at = prefix ? `${prefix}.${key}` : key
    if (value && typeof value === 'object') flatten(value, at, out)
    else if (typeof value === 'string') out[at] = value
  }
  return out
}

/** The reverse of flatten, keeping the source catalog's key order. */
export function unflatten(flat, order) {
  const tree = {}
  for (const key of order) {
    if (!(key in flat)) continue
    const parts = key.split('.')
    let node = tree
    for (const part of parts.slice(0, -1)) node = node[part] ??= {}
    node[parts[parts.length - 1]] = flat[key]
  }
  return tree
}

const TOKEN_PATTERN = /\{\w+\}|<\/?\w+>/g

/** "Hi {name}, <b>go</b>" -> { text: "Hi ⟦0⟧, ⟦1⟧go⟦2⟧", tokens: ["{name}", "<b>", "</b>"] } */
export function mask(text) {
  const tokens = []
  const masked = text.replace(TOKEN_PATTERN, (token) => {
    tokens.push(token)
    return `⟦${tokens.length - 1}⟧`
  })
  return { text: masked, tokens }
}

/** Puts the tokens back; null when the translation lost or invented one. */
export function unmask(text, tokens) {
  const seen = new Set()
  const restored = text.replace(/⟦(\d+)⟧/g, (whole, index) => {
    const token = tokens[Number(index)]
    if (token === undefined) return whole
    seen.add(Number(index))
    return token
  })
  if (seen.size !== tokens.length || /⟦\d+⟧/.test(restored)) return null
  return restored
}

/** The placeholders a message uses, for comparing a translation with its source. */
export const placeholdersOf = (text) => (text.match(TOKEN_PATTERN) ?? []).sort().join(' ')

function catalogLocales() {
  return readdirSync(LOCALES_DIR)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
}

/** locales/index.ts, listing every catalog in the folder. */
function writeIndex() {
  const locales = catalogLocales().sort((a, b) => (a === SOURCE_LOCALE ? -1 : b === SOURCE_LOCALE ? 1 : a.localeCompare(b)))
  const ident = (code) => code.replace(/-/g, '_')
  const lines = [
    '// The catalogs the app ships with. English is the source: every key exists',
    '// there, and any other catalog may lack keys, which then show in English.',
    '//',
    '// Regenerated by `npm run i18n:translate` when it writes a catalog; adding a',
    '// <locale>.json here by hand works too, as long as it is listed below.',
    '',
    ...locales.map((code) => `import ${ident(code)} from "./${code}.json"`),
    '',
    `export const SOURCE_LOCALE = "${SOURCE_LOCALE}"`,
    '',
    'export const catalogs: Record<string, unknown> = {',
    ...locales.map((code) => (ident(code) === code ? `  ${code},` : `  "${code}": ${ident(code)},`)),
    '}',
    '',
  ]
  writeFileSync(path.join(LOCALES_DIR, 'index.ts'), lines.join('\n'))
}

function check() {
  const source = flatten(readJson(path.join(LOCALES_DIR, `${SOURCE_LOCALE}.json`), {}))
  let broken = 0
  for (const locale of catalogLocales().filter((code) => code !== SOURCE_LOCALE)) {
    const target = flatten(readJson(path.join(LOCALES_DIR, `${locale}.json`), {}))
    const sources = readJson(path.join(SOURCES_DIR, `${locale}.json`), {})
    const missing = Object.keys(source).filter((key) => !(key in target))
    const stale = Object.keys(target).filter((key) => key in source && sources[key] !== undefined && sources[key] !== source[key])
    const extra = Object.keys(target).filter((key) => !(key in source))
    const bad = Object.keys(target).filter((key) => key in source && placeholdersOf(target[key]) !== placeholdersOf(source[key]))
    broken += bad.length
    console.log(`${locale}: ${Object.keys(target).length}/${Object.keys(source).length} translated, ${missing.length} missing, ${stale.length} stale, ${extra.length} unused, ${bad.length} with wrong placeholders`)
    for (const key of bad) console.log(`  placeholders differ: ${key}`)
  }
  process.exit(broken ? 1 : 0)
}

async function loadProvider(name) {
  if (!name) {
    throw new Error('Set TRANSLATOR to a provider in scripts/translators/ (e.g. TRANSLATOR=pseudo). See scripts/translators/README.md.')
  }
  if (!/^[\w-]+$/.test(name)) throw new Error(`Bad TRANSLATOR name: ${name}`)
  const file = path.join(ROOT, 'scripts', 'translators', `${name}.mjs`)
  if (!existsSync(file)) throw new Error(`No provider at scripts/translators/${name}.mjs`)
  const provider = await import(pathToFileURL(file).href)
  if (typeof provider.translate !== 'function') throw new Error(`${name}.mjs must export translate(texts, { from, to })`)
  return provider
}

async function translateLocale(locale, { all, dryRun }) {
  if (!LOCALE_PATTERN.test(locale) || locale === SOURCE_LOCALE) throw new Error(`Not a target locale: ${locale}`)
  const sourceTree = readJson(path.join(LOCALES_DIR, `${SOURCE_LOCALE}.json`), {})
  const source = flatten(sourceTree)
  const targetFile = path.join(LOCALES_DIR, `${locale}.json`)
  const sourcesFile = path.join(SOURCES_DIR, `${locale}.json`)
  const target = flatten(readJson(targetFile, {}))
  const sources = readJson(sourcesFile, {})

  const todo = Object.keys(source).filter((key) => all || !(key in target) || (sources[key] !== undefined && sources[key] !== source[key]))
  console.log(`${locale}: ${todo.length} of ${Object.keys(source).length} keys to translate`)
  if (!todo.length || dryRun) return

  const provider = await loadProvider(process.env.TRANSLATOR?.trim())
  const batchSize = provider.batchSize ?? 50
  let rejected = 0
  for (let start = 0; start < todo.length; start += batchSize) {
    const keys = todo.slice(start, start + batchSize)
    const masked = keys.map((key) => mask(source[key]))
    const results = await provider.translate(
      masked.map((item) => item.text),
      { from: SOURCE_LOCALE, to: locale, keys }
    )
    if (!Array.isArray(results) || results.length !== keys.length) {
      throw new Error(`Provider returned ${results?.length} results for ${keys.length} texts`)
    }
    keys.forEach((key, index) => {
      const restored = typeof results[index] === 'string' ? unmask(results[index], masked[index].tokens) : null
      if (restored === null) {
        rejected += 1
        console.warn(`  kept English (placeholders lost): ${key}`)
        return
      }
      target[key] = restored
      sources[key] = source[key]
    })
    console.log(`  ${Math.min(start + batchSize, todo.length)} / ${todo.length}`)
  }

  // Keys English no longer has are dropped, so a catalog never carries dead text.
  for (const key of Object.keys(target)) if (!(key in source)) delete target[key]
  for (const key of Object.keys(sources)) if (!(key in source)) delete sources[key]

  mkdirSync(SOURCES_DIR, { recursive: true })
  writeJson(targetFile, unflatten(target, Object.keys(source)))
  writeJson(sourcesFile, sources)
  writeIndex()
  console.log(`wrote locales/${locale}.json${rejected ? ` (${rejected} kept in English)` : ''}`)
}

async function main() {
  const args = process.argv.slice(2)
  if (args.includes('--check')) return check()
  const locales = args.filter((arg) => !arg.startsWith('--'))
  if (!locales.length) {
    console.error('Usage: TRANSLATOR=<provider> node scripts/i18n-translate.mjs <locale>... [--all] [--dry-run]\n       node scripts/i18n-translate.mjs --check')
    process.exit(2)
  }
  for (const locale of locales) await translateLocale(locale, { all: args.includes('--all'), dryRun: args.includes('--dry-run') })
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
if (isMain) {
  main().catch((error) => {
    console.error(error.message ?? error)
    process.exit(1)
  })
}
